# Generates WasmSmoke/SigProbes.g.cs: one probe per distinct wasm32 call signature used by BRUTAL's Vulkan
# function-pointer structs. Each probe creates a JS function with Module.addFunction(fn, sig), wraps it in the
# *real* BRUTAL fnptr struct of a representative Vulkan command (via its explicit operator from PfnVkVoidFunction)
# and calls .Invoke(default, ...) from interpreted C#. A missing Mono interp->native trampoline aborts the runtime,
# so the driver runs each probe in its own page load (?tests=Pnn).
# Usage: python3 -I gen_sig_probes.py <BRUTAL/Brutal.Vulkan> <out.cs>
import re, os, sys, glob, collections
root, out = sys.argv[1], sys.argv[2]
gen = os.path.join(root, 'Generated')
src = open(os.path.join(gen, 'Functions.gen.cs')).read()
enums = {}
for f in glob.glob(os.path.join(gen, 'Enums', '**', '*.cs'), recursive=True):
    for m in re.finditer(r'enum (\w+) : (\w+)', open(f).read()):
        enums[m.group(1)] = m.group(2)
handles = {os.path.basename(f).split('.')[0] for f in glob.glob(os.path.join(gen, 'Handles', '**', '*.cs'), recursive=True)}
I64 = {'long', 'ulong', 'ByteSize64', 'VkDeviceAddress', 'VkFlags64'}
def kind(t):
    if t.endswith('*'): return 'i'
    if t == 'void': return 'v'
    if t in I64: return 'j'
    if t == 'float': return 'f'
    if t == 'double': return 'd'
    if t in enums: return 'j' if enums[t] in ('long', 'ulong') else 'i'
    return 'i'
def split_args(s):
    res, depth, cur = [], 0, ''
    for ch in s:
        depth += (ch == '<') - (ch == '>')
        if ch == ',' and depth == 0: res.append(cur.strip()); cur = ''
        else: cur += ch
    res.append(cur.strip()); return res
sigs = collections.OrderedDict()
for m in re.finditer(r'public readonly unsafe struct (\w+)\(\s*delegate\* unmanaged\[Cdecl\]<(.*?)> handle\s*\)', src, re.S):
    name, args = m.group(1), split_args(' '.join(m.group(2).split()))
    ks = [kind(a) for a in args]
    sigs.setdefault(ks[-1] + ''.join(ks[:-1]), []).append((name, args))
ordered = sorted(sigs.items(), key=lambda kv: -len(kv[1]))
lines = ['// <auto-generated> by tools/gen_sig_probes.py from BRUTAL/Brutal.Vulkan/Generated/Functions.gen.cs </auto-generated>',
         'using System.Runtime.InteropServices.JavaScript;', 'using Brutal.VulkanApi;', '',
         'public static unsafe partial class SmokeTests', '{',
         '    [JSImport("makeJsSig", "main.js")] internal static partial int MakeJsSig(string sig);',
         '    [JSImport("jsSigCalls", "main.js")] internal static partial int JsSigCalls(string sig);', '',
         '    static void RunSigProbes()', '    {']
bodies = []
for i, (sig, fns) in enumerate(ordered, 1):
    # prefer a Vk* command (has the explicit operator) as representative
    rep = next(((n, a) for n, a in fns if n.startswith('Vk')), fns[0])
    name, args = rep
    pid = f'P{i:02d}'
    lines.append(f'        RunProbe("{pid}", "sig {sig} ({len(fns)} BRUTAL fns, e.g. {name})", Probe_{sig});')
    nparams = len(args) - 1
    call_args = ', '.join(['default'] * nparams)
    if name.startswith('Pfn'):
        cast = f'new {name}((delegate* unmanaged[Cdecl]<{", ".join(args)}>)(nint)MakeJsSig("{sig}"))'
    else:
        cast = f'({name})new PfnVkVoidFunction((delegate* unmanaged[Cdecl]<void>)(nint)MakeJsSig("{sig}"))'
    invoke = f'f.Invoke({call_args});' if args[-1] == 'void' else f'_ = f.Invoke({call_args});'
    bodies += [f'    static string Probe_{sig}()', '    {', f'        var f = {cast};', f'        {invoke}',
               f'        return $"{name}.Invoke(...) -> JS addFunction(\'{sig}\') ok, jsCalls={{JsSigCalls("{sig}")}}";', '    }', '']
lines += ['    }', ''] + bodies + ['}']
open(out, 'w').write('\n'.join(lines) + '\n')
print(f'wrote {out}: {len(ordered)} probes covering {sum(len(v) for v in sigs.values())} fnptr structs')
