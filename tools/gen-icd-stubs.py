#!/usr/bin/env python3
"""Generate the exact-signature "unsupported" stubs of the web ICD (src/Brutal.Vulkan.WebGpu).

BRUTAL's VkInstance/VkDevice function tables ask vkGetInstanceProcAddr/vkGetDeviceProcAddr for every command they
know and store the result unchecked; calling a NULL managed function pointer aborts the .NET runtime. The ICD
therefore hands out a correctly typed function for every name. Commands it does not implement get a generated stub
that throws VulkanUnsupportedException(name).

Input : $BRUTAL/Brutal.Vulkan/Generated/Functions.gen.cs (one `public readonly unsafe struct VkXxx(delegate*
        unmanaged[Cdecl]<...> handle)` per command; the browser flavor rewrites these to managed `delegate*<...>`).
Output: src/Brutal.Vulkan.WebGpu/Generated/Stubs.g.cs       one static method per command
        src/Brutal.Vulkan.WebGpu/Generated/StubTable.g.cs   name -> (nint)new VkXxx(&IcdStubs.vkXxx).Invoke
Taking the address through BRUTAL's own wrapper-struct constructor makes the C# compiler verify every stub signature
against the binding. The callback typedefs (PfnVk*) are not commands and are skipped. The four global commands
(vkCreateInstance, vkEnumerateInstance*) have no wrapper struct in Functions.gen.cs and are implemented by hand.

Usage (from the repository root):
    python3 -I tools/gen-icd-stubs.py [--brutal ../BRUTAL] [--out src/Brutal.Vulkan.WebGpu/Generated] [--check]
The BRUTAL checkout defaults to $BRUTAL_SRC, else ../BRUTAL next to the repository. --check exits 1 when the checked-in
files differ from what would be generated (no files are written).
"""
import argparse
import os
import re
import sys

ALIAS_RE = re.compile(r'^global using (\w+) = ([\w.]+);', re.M)
TYPE_DECL_RE = re.compile(r'\b(?:enum|struct|class|interface)\s+(\w+)')
STRUCT_RE = re.compile(
    r'public readonly unsafe struct (\w+)\(\s*delegate\*\s*unmanaged\s*\[\s*Cdecl\s*\]\s*<(.*?)>\s*handle\s*\)', re.S)
TYPE_RE = re.compile(r'[A-Za-z_][\w.]*\**')

HEADER = """// <auto-generated>
//   Generated by tools/gen-icd-stubs.py from {source} ({count} commands).
//   Do not edit by hand. Regenerate from the repository root with:  python3 -I tools/gen-icd-stubs.py
// </auto-generated>
#nullable enable
using Brutal.VulkanApi;
using Brutal.VulkanApi.Android;
using Brutal.VulkanApi.Metal;
using Brutal.VulkanApi.Wayland;
using Brutal.VulkanApi.Win32;
using Brutal.VulkanApi.Xcb;
using Brutal.VulkanApi.Xlib;

namespace Brutal.Vulkan.WebGpu;
"""


def command_name(struct_name: str) -> str:
    # VkCmdDraw -> vkCmdDraw, VxDestroyImages -> vxDestroyImages
    return struct_name[0].lower() + struct_name[1:]


def type_resolver(brutal_vulkan: str):
    """BRUTAL declares assembly-local `global using VkXxxFlags = Brutal.VulkanApi.VkFlags;` aliases (Generated/Globals.gen.cs).
    Inside BRUTAL's namespace a declared type of the same name wins over the alias; outside it (our assembly) the alias would
    not exist at all, so names that are only aliases are replaced by their targets."""
    aliases = dict(ALIAS_RE.findall(open(os.path.join(brutal_vulkan, 'Generated', 'Globals.gen.cs'), encoding='utf-8').read()))
    declared = set()
    for root, _, files in os.walk(brutal_vulkan):
        for f in files:
            if f.endswith('.cs') and f != 'Globals.gen.cs':
                declared.update(TYPE_DECL_RE.findall(open(os.path.join(root, f), encoding='utf-8').read()))

    def resolve(t: str) -> str:
        stars = len(t) - len(t.rstrip('*'))
        base = t.rstrip('*')
        while base not in declared and base in aliases:
            target = aliases[base]
            base = target.rsplit('.', 1)[-1] if target.startswith('Brutal.VulkanApi.') else target
        return base + '*' * stars
    return resolve


def parse(functions_path: str, resolve):
    src = open(functions_path, encoding='utf-8').read()
    commands = []
    for struct_name, sig in STRUCT_RE.findall(src):
        if not (struct_name.startswith('Vk') or struct_name.startswith('Vx')):
            continue  # PfnVk* callback typedefs
        types = [t.strip() for t in sig.split(',')]
        for t in types:
            if not TYPE_RE.fullmatch(t):
                raise SystemExit(f'unexpected type {t!r} in {struct_name}')
        types = [resolve(t) for t in types]
        commands.append((struct_name, command_name(struct_name), types[:-1], types[-1]))
    if not commands:
        raise SystemExit(f'no command structs found in {functions_path}')
    return commands


def gen_stubs(commands, source: str) -> str:
    lines = [HEADER.format(source=source, count=len(commands)),
             '/// <summary>One stub per Vulkan command with BRUTAL\'s exact signature; each throws <see cref="VulkanUnsupportedException"/>.</summary>',
             'internal static unsafe class IcdStubs',
             '{']
    for _, name, params, ret in commands:
        args = ', '.join(f'{t} a{i}' for i, t in enumerate(params))
        lines.append(f'    internal static {ret} {name}({args}) => throw new VulkanUnsupportedException("{name}");')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def gen_table(commands, source: str) -> str:
    lines = [HEADER.format(source=source, count=len(commands)),
             '/// <summary>Name to managed function pointer for every generated stub (see <see cref="IcdStubs"/>).</summary>',
             'internal static unsafe class IcdStubTable',
             '{',
             f'    /// <summary>Number of commands with a generated stub.</summary>',
             f'    internal const int Count = {len(commands)};',
             '',
             '    /// <summary>Adds every stub; BRUTAL\'s wrapper-struct constructors type-check each signature.</summary>',
             '    internal static void AddAll(Dictionary<string, nint> table)',
             '    {']
    for struct_name, name, _, _ in commands:
        lines.append(f'        table["{name}"] = (nint)new {struct_name}(&IcdStubs.{name}).Invoke;')
    lines += ['    }', '}']
    return '\n'.join(lines) + '\n'


def main() -> int:
    here = os.path.dirname(os.path.abspath(__file__))
    repo = os.path.dirname(here)
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--brutal', default=os.environ.get('BRUTAL_SRC') or os.path.join(os.path.dirname(repo), 'BRUTAL'))
    ap.add_argument('--out', default=os.path.join(repo, 'src', 'Brutal.Vulkan.WebGpu', 'Generated'))
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()

    functions = os.path.join(a.brutal, 'Brutal.Vulkan', 'Generated', 'Functions.gen.cs')
    if not os.path.isfile(functions):
        print(f'error: {functions} not found (set --brutal or BRUTAL_SRC)', file=sys.stderr)
        return 2
    commands = parse(functions, type_resolver(os.path.join(a.brutal, 'Brutal.Vulkan')))
    source = '$BRUTAL/Brutal.Vulkan/Generated/Functions.gen.cs'
    outputs = {'Stubs.g.cs': gen_stubs(commands, source), 'StubTable.g.cs': gen_table(commands, source)}

    stale = []
    for file, text in outputs.items():
        path = os.path.join(a.out, file)
        old = open(path, encoding='utf-8').read() if os.path.exists(path) else None
        if old != text:
            stale.append(path)
            if not a.check:
                os.makedirs(a.out, exist_ok=True)
                with open(path, 'w', encoding='utf-8', newline='\n') as f:
                    f.write(text)
    if a.check:
        for p in stale:
            print(f'stale: {p}', file=sys.stderr)
        return 1 if stale else 0
    print(f'{len(commands)} command stubs; {"updated " + ", ".join(os.path.basename(p) for p in stale) if stale else "up to date"}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
